//
// 【1】3語とも「独立した軸」にする。文章を切り分けただけにしない
//
//   1語だけが意味を持ち、残りが糊のような言葉だと、答えを聞いた瞬間に
//   「変わったのはあの語だ」と逆算されてしまう。
//
//   だめ: 結婚相手 / 譲れない / 条件
//         →「譲れない」「条件」は差し替えようがない糊。実質1軸の問いなので、
//           変わったのが「結婚相手」だと一発で分かる
//   よい: 夏 / 恋愛 / 曲
//         → 季節・テーマ・カテゴリの3軸。どれが変わっていてもおかしくないので、
//           答えから逆算できない
//
//   使ってはいけない語: こと / もの / 条件 / 瞬間 / 方法 / 場面 / 理由 /
//                       決め手 / 過ごし方 / いちばん / 譲れない / 必要な
//   （これらは「答えの型」を示すだけで、差し替えても方向性が変わらない）
//
// 【2】どの語を変えても、思考が別の方向へ傾くこと
//
//   夏→冬 なら季節が、恋愛→友情 ならテーマが、曲→映画 ならジャンルが動く。
//   3つとも動かせるからこそ、変わった語を特定できない。
//
// 【3】答えの「型」は変えない
//
//   曲を映画に差し替えると、異端だけ映画のタイトルを書くので即バレする。
//   差し替えるなら 男性→女性、犬→猫 のように、答えの型が変わらない範囲で。
//
// 【4】遠すぎ・近すぎの両方を避ける
//
//   遠すぎ: 春にうれしいこと / 秋にうれしいこと
//           → 答えが1つも重ならず、異端だけ浮く
//   近すぎ: 遠足で行きたい場所 / 修学旅行で行きたい場所
//           → 傾向が動かず、誰にも当てられない
//   目安は「答えの半分は重なるが、残り半分に偏りが出る」くらい。
//
// 足すときの手順:
//   1. 3語それぞれについて「これを別の語に変えたらどうなるか」を言えるか確かめる
//      （言えない語があれば、それは糊なので作り直す）
//   2. 3語をつないで自然な問いになるか声に出す
//   3. その問いの答えが人によって割れるか確かめる
//   4. 差し替え後、答えの型は同じまま傾向だけ動くか確かめる

